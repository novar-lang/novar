//! `novar.lock`: the exact versions a build uses, so every machine resolves the same graph.

use std::path::Path;

use semver::Version;
use serde::{Deserialize, Serialize};

pub const LOCKFILE: &str = "novar.lock";

#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
pub struct Lock {
    #[serde(default, rename = "package")]
    pub packages: Vec<Locked>,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Locked {
    pub name: String,
    pub version: Version,
    /// `registry` or `path+<dir>`; the root package has no source.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub checksum: Option<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub dependencies: Vec<String>,
}

impl Lock {
    pub fn parse(text: &str) -> Result<Lock, String> {
        toml::from_str(text).map_err(|e| format!("invalid {LOCKFILE}: {}", e.message()))
    }

    pub fn read(dir: &Path) -> Result<Option<Lock>, String> {
        match std::fs::read_to_string(dir.join(LOCKFILE)) {
            Ok(text) => Lock::parse(&text).map(Some),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(format!("cannot read {LOCKFILE}: {e}")),
        }
    }

    pub fn write(&self, dir: &Path) -> Result<(), String> {
        let mut sorted = self.clone();
        sorted
            .packages
            .sort_by(|a, b| a.name.cmp(&b.name).then(a.version.cmp(&b.version)));
        let body = toml::to_string_pretty(&sorted).map_err(|e| e.to_string())?;
        let text = format!("# Generated by nvpm. Do not edit by hand.\n{body}");
        std::fs::write(dir.join(LOCKFILE), text)
            .map_err(|e| format!("cannot write {LOCKFILE}: {e}"))
    }

    pub fn get(&self, name: &str) -> Option<&Locked> {
        self.packages.iter().find(|p| p.name == name)
    }
}
