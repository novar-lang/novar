//! Single-binary deployment: `novar build --serve app.nv` copies this executable and appends
//! the program to it. When the copy starts and finds the program, it serves it directly.
//!
//! On macOS the copy keeps the executable's original ad-hoc signature, which still covers the
//! executable part; `codesign --verify --strict` rejects the trailing payload but the loader runs it.
//!
//! Layout of a bundled binary: `[novar executable][JSON program][u64 LE JSON length]["NOVARAPP"]`,
//! where the JSON holds every source file of the program (see [`Bundle`]).

use std::fs::File;
use std::io::{Read, Seek, SeekFrom, Write};
use std::path::Path;

use crate::{CliError, failed};

pub use novar_modules::Image as Bundle;

const MAGIC: &[u8; 8] = b"NOVARAPP";
const FOOTER: u64 = 16;

/// The program embedded in `exe`, with the length of the plain executable before it.
fn read_payload(exe: &Path) -> std::io::Result<Option<(String, u64)>> {
    let mut f = File::open(exe)?;
    let len = f.metadata()?.len();
    if len < FOOTER {
        return Ok(None);
    }
    f.seek(SeekFrom::End(-(FOOTER as i64)))?;
    let mut footer = [0u8; FOOTER as usize];
    f.read_exact(&mut footer)?;
    if &footer[8..] != MAGIC {
        return Ok(None);
    }
    let src_len = u64::from_le_bytes(footer[..8].try_into().expect("8 bytes"));
    if src_len + FOOTER > len {
        return Ok(None);
    }
    f.seek(SeekFrom::Start(len - FOOTER - src_len))?;
    let mut src = vec![0u8; src_len as usize];
    f.read_exact(&mut src)?;
    Ok(String::from_utf8(src)
        .ok()
        .map(|s| (s, len - FOOTER - src_len)))
}

/// The program bundled into the running executable, if any.
pub fn embedded() -> Option<Bundle> {
    let exe = std::env::current_exe().ok()?;
    let (json, _) = read_payload(&exe).ok().flatten()?;
    serde_json::from_str(&json).ok()
}

/// Writes a copy of this executable with `source` appended to `out`.
pub fn write_bundle(bundle: &Bundle, out: &Path) -> std::io::Result<()> {
    let source = serde_json::to_string(bundle).map_err(std::io::Error::other)?;
    let exe = std::env::current_exe()?;
    // Rebundling a bundle must not stack payloads: copy only the plain executable.
    let base_len = match read_payload(&exe)? {
        Some((_, base)) => base,
        None => std::fs::metadata(&exe)?.len(),
    };
    let mut input = File::open(&exe)?.take(base_len);
    let mut output = File::create(out)?;
    std::io::copy(&mut input, &mut output)?;
    output.write_all(source.as_bytes())?;
    output.write_all(&(source.len() as u64).to_le_bytes())?;
    output.write_all(MAGIC)?;
    output.flush()?;
    drop(output);
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(out, std::fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

/// A multi-stage Dockerfile that builds the bundled server and ships only that binary.
pub fn dockerfile(program: &str) -> String {
    format!(
        "\
# syntax=docker/dockerfile:1
# Generated by `novar build --serve`. Build with: docker build -t my-service .

FROM rust:slim-bookworm AS builder
ARG NOVAR_REPO=https://github.com/ntsation/novar
ARG NOVAR_REF=main
RUN apt-get update && apt-get install -y --no-install-recommends git pkg-config libssl-dev ca-certificates \\
    && rm -rf /var/lib/apt/lists/*
RUN rustup toolchain install nightly --profile minimal && rustup default nightly
RUN git clone --depth 1 --branch ${{NOVAR_REF}} ${{NOVAR_REPO}} /novar \\
    && cargo build --release --manifest-path /novar/Cargo.toml -p novar_cli
WORKDIR /app
COPY {program} .
RUN mkdir -p /out && /novar/target/release/novar build --serve {program} -o /out/service

FROM gcr.io/distroless/cc-debian12:nonroot
COPY --from=builder /out/service /service
ENV PORT=8080
EXPOSE 8080
USER nonroot
ENTRYPOINT [\"/service\"]
"
    )
}

/// `novar build --serve <file> [-o out] [--dockerfile]`
pub fn build_serve(file: &str, flags: &[&str]) -> Result<(), CliError> {
    let mut out = None;
    let mut docker = false;
    let mut it = flags.iter();
    while let Some(flag) = it.next() {
        match *flag {
            "--dockerfile" => docker = true,
            "-o" => out = Some(it.next().ok_or(CliError::Usage)?.to_string()),
            _ => return Err(CliError::Usage),
        }
    }
    let checked = crate::check_project(file)?;
    if novar_server::routes(&checked.hir).is_empty() {
        return failed("no `@endpoint` functions found, there is nothing to serve");
    }
    let stem = Path::new(file)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("service");
    let mut out = out.unwrap_or_else(|| stem.to_string());
    // Windows only runs files that end in `.exe`.
    if !std::env::consts::EXE_SUFFIX.is_empty() && !out.ends_with(std::env::consts::EXE_SUFFIX) {
        out.push_str(std::env::consts::EXE_SUFFIX);
    }
    write_bundle(&checked.bundle, Path::new(&out))
        .or_else(|e| failed(format!("cannot write `{out}`: {e}")))?;
    eprintln!("wrote {out}  (single binary; run it with --port N, --host H, --seed FILE, --live)");
    if docker {
        let dir = Path::new(file)
            .parent()
            .filter(|p| !p.as_os_str().is_empty())
            .unwrap_or(Path::new("."));
        let name = Path::new(file)
            .file_name()
            .and_then(|s| s.to_str())
            .unwrap_or(file);
        let path = dir.join("Dockerfile");
        std::fs::write(&path, dockerfile(name))
            .or_else(|e| failed(format!("cannot write the Dockerfile: {e}")))?;
        eprintln!("wrote {}", path.display());
    }
    Ok(())
}
